/*
 * Interrupt handlers. Each one hands off to the HAL, which checks and clears
 * the peripheral's flags and then calls the matching HAL_xxxCallback().
 * Vector table entries live in startup/startup_ARMCM3.c (index = 16 + IRQn).
 *
 * Priorities (set in mspInit.c / usart.c, 0 = most urgent), ordered by how
 * soon each source must be serviced before something breaks:
 *   SPI1   1  next byte must be read within ~1 byte time (4 us at 2 MHz) or it overruns
 *   TIM1   2  must finish within the 1 ms PWM period (CCR is preloaded)
 *   ADC1   3  result just has to be read before the next 1 kHz conversion
 *   USART1 6  late service only slows the output, nothing is lost
 *   SysTick 15 (TICK_INT_PRIORITY) - HAL default
 * The PWM itself is generated by TIM1 hardware and never depends on the CPU.
 * SysTick is lowest, so never call HAL_Delay() or HAL timeouts from an ISR,
 * and only call printf() from main(): it waits for room in the TX buffer.
 */
#include "stm32f1xx.h"
#include "stm32f1xx_hal.h"

extern TIM_HandleTypeDef htim1;
extern ADC_HandleTypeDef hadc1;
extern SPI_HandleTypeDef hspi1;

void SysTick_Handler(void)    { HAL_IncTick(); }
void TIM1_UP_IRQHandler(void) { HAL_TIM_IRQHandler(&htim1); }
void TIM1_CC_IRQHandler(void) { HAL_TIM_IRQHandler(&htim1); }
void ADC1_2_IRQHandler(void)  { HAL_ADC_IRQHandler(&hadc1); }
void SPI1_IRQHandler(void)    { HAL_SPI_IRQHandler(&hspi1); }
